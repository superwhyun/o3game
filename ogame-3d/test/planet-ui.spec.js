import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require=createRequire(import.meta.url);
const mongoose=require('../../server/node_modules/mongoose');
const fixtureFile=process.env.PLANET_UI_FIXTURE_FILE;
test.skip(!fixtureFile,'Start isolated server/scripts/previewPlanetAreas.js and set PLANET_UI_FIXTURE_FILE.');
let fixture;
test.beforeAll(async()=>{fixture=JSON.parse(readFileSync(fixtureFile,'utf8'));if(!/planet_area_ui_test/.test(fixture.uri))throw new Error('Dedicated test DB required');await mongoose.connect(fixture.uri);});
test.afterAll(async()=>{await mongoose.disconnect();});
async function finishQueues(page){
  const Queue=require('../../server/models/BuildingQueue');
  await Queue.updateMany({userId:fixture.userId,applied:false,status:{$in:['building','pending']}},{$set:{endTime:new Date(Date.now()-100),startTime:new Date(Date.now()-2000)}});
  await page.evaluate(()=>window.uiManager.syncUserDataFromServer());
}
test('real UI: full planet, demolition, new building, global terraforming, switching and reload',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(({token,user})=>{localStorage.setItem('token',token);localStorage.setItem('user',JSON.stringify(user));},fixture);
  await page.goto('/');await page.locator('.holo-btn[data-view="buildings"]').click();
  await expect(page.locator('#planet-development')).toContainText('남은 0칸');
  await page.locator('#planet-development').click();
  await expect(page.locator('#planet-development-details')).toContainText('금속 +20%');
  await page.locator('.modal-close').click();
  await page.locator('[data-entity="metalMine"]').click();
  await expect(page.locator('.entity-row.is-selected .entity-status')).toHaveText('면적 부족');
  await expect(page.locator('.entity-row.is-selected [data-command="building"]')).toBeDisabled();
  page.once('dialog',dialog=>dialog.accept());await page.locator('.entity-row.is-selected [data-command="demolish"]').click();
  await expect(page.locator('#buildings-panel-queue')).toContainText('철거');
  await finishQueues(page);await expect(page.locator('#planet-development')).toContainText('남은 1칸');
  await page.locator('[data-entity="crystalMine"]').click();await page.locator('.entity-row.is-selected [data-command="building"]').click();
  await expect(page.locator('#planet-development')).toContainText('예약 1칸');
  await finishQueues(page);await expect(page.locator('#planet-development')).toContainText('남은 0칸');
  await page.locator('#planet-select').selectOption('1');
  await expect(page.locator('#planet-development')).toContainText('테라포밍 거점');
  await expect(page.locator('#planet-development')).toContainText('전체 400칸');
  await page.locator('.holo-btn[data-view="research"]').click();
  await page.locator('[data-entity="terraforming"]').click();
  await expect(page.locator('#research-browser')).toContainText('단계당 +2%p');
  await page.locator('.entity-row.is-selected [data-command="research"]').click();
  await expect(page.locator('#research-panel-queue')).toContainText('테라포밍');
  await finishQueues(page);await expect(page.locator('#planet-development')).toContainText('가용률 42%');
  await page.locator('#planet-select').selectOption('0');
  await expect(page.locator('#planet-development')).toContainText('남은 2칸');
  await page.reload();await page.locator('.holo-btn[data-view="buildings"]').click();
  await expect(page.locator('#planet-development')).toContainText('가용률 42%');
  await expect(page.locator('#planet-select')).toHaveValue('0');
  await page.screenshot({path:new URL('../../artifacts/planet-ui/desktop.png',import.meta.url).pathname});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:new URL('../../artifacts/planet-ui/mobile.png',import.meta.url).pathname});
  await expect(page.locator('#planet-select')).toBeVisible();
  expect(errors).toEqual([]);
});
