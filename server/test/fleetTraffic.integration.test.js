const test = require('node:test');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const { MongoMemoryReplSet } = require('mongodb-memory-server');
test('traffic exposes all commanders, sanitized external endpoints, grouped counts and return legs', async () => {
 const db = await MongoMemoryReplSet.create({ replSet: { count: 1 } });
 await mongoose.connect(db.getUri('traffic_test'));
 const Movement = require('../models/FleetMovement');
 const traffic = require('../services/FleetTrafficService');
 let httpServer;
 try {
  await Movement.init();
  const me = new mongoose.Types.ObjectId(), other = new mongoose.Types.ObjectId();
  const origin = { galaxy: 1, system: 1, planet: 4 }, remote = { galaxy: 2, system: 1, planet: 12 };
  const now = Date.now();
  const base = { userId: other, username: 'Other', mission: 'spy', fleet: { espionageProbe: 1 }, cargo: { metal: 123 }, requestId: 'secret', origin: remote, destination: origin, startTime: new Date(now - 5000), arrivalTime: new Date(now + 5000) };
  await Movement.insertMany([base, { ...base, requestId: 'secret2' }, { ...base, userId: me, requestId: 'secret3', origin, destination: { ...origin, planet: 8 } }, { ...base, requestId: 'secret4', status: 'returning', returnStartTime: new Date(now), returnTime: new Date(now + 10000) }, { ...base, requestId: 'secret5', status: 'completed' }, { ...base, requestId: 'secret6', origin: remote, destination: { galaxy: 3, system: 1, planet: 1 } }]);
  const view = await traffic.list(me, { galaxy: '1', system: '1', limit: '1' });
  assert.equal(view.total, 4); assert.equal(view.routes.length, 3); assert.equal(view.movements.length, 1); assert.ok(view.nextCursor);
  const inbound = view.routes.find(r => r.count === 2);
  assert.deepEqual(inbound.from, { galaxy: 2, system: 1 }); assert.deepEqual(inbound.to, { planet: 4 });
  assert.equal(inbound.isSelf, false);
  assert.ok(view.routes.some(r => r.isSelf));
  const returning = view.routes.find(r => r.status === 'returning');
  assert.deepEqual(returning.from, { planet: 4 }); assert.deepEqual(returning.to, { galaxy: 2, system: 1 });
  assert.equal(+new Date(returning.startedAt), now);
  for (const row of [...view.routes, ...view.movements]) for (const key of ['fleet', 'cargo', 'mission', 'requestId', 'formationNameAtLaunch']) assert.equal(row[key], undefined);
  const detail = await traffic.list(me, { galaxy: 1, system: 1, route: inbound.routeId, limit: 100 });
  assert.equal(detail.movements.length, 2);
  const page2 = await traffic.list(me, { galaxy: 1, system: 1, cursor: view.nextCursor }); assert.equal(page2.movements.length, 3);
  await assert.rejects(traffic.list(me, { galaxy: 0, system: 1 }), /좌표/);
  await assert.rejects(traffic.list(me, { galaxy: 1, system: 1, cursor: 'bad' }), /페이지/);
  await Movement.create({ ...base, requestId: 'legacy-return', status: 'returning', returnTime: new Date(now + 10000) });
  const legacy = await traffic.list(me, { galaxy: 1, system: 1 });
  const legacyDetail = legacy.movements.find(r => r.status === 'returning' && +new Date(r.startedAt) === now);
  assert.ok(legacyDetail);
  process.env.JWT_SECRET = 'traffic-http-integration-secret-only-2026';
  const User = require('../models/User');
  await User.create({ _id: me, username: 'Observer', email: 'observer@test.invalid', password: require('node:crypto').randomUUID(), planets: [{ galaxy: 1, system: 1, planet: 4 }] });
  const app = require('express')(); app.use('/api/game', require('../routes/game'));
  httpServer = await new Promise(resolve => { const server = app.listen(0, () => resolve(server)); });
  const url = `http://localhost:${httpServer.address().port}/api/game/galaxy/traffic?galaxy=1&system=1`;
  assert.equal((await fetch(url)).status, 401);
  const token = require('jsonwebtoken').sign({ userId: String(me) }, process.env.JWT_SECRET);
  const response = await fetch(url, { headers: { Authorization: `Bearer ${token}` } });
  assert.equal(response.status, 200); assert.equal((await response.json()).total, 5);
  const explain = await Movement.find(traffic.scope(1, 1)).explain('executionStats');
  assert.ok(JSON.stringify(explain.queryPlanner.winningPlan).includes('IXSCAN'));
 } finally { if (httpServer) await new Promise(resolve => httpServer.close(resolve)); await mongoose.disconnect(); await db.stop(); }
});
